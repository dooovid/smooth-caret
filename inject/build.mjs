// Builds dist/smooth-caret-inject.js: the caret (extension/content.js), the
// settings UI (extension/ui.js with popup.html's markup and popup.css) and the
// menu window (inject/), as one script to paste into DevTools.
//
//   node inject/build.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = (path) => readFileSync(new URL(path, root), 'utf8');

// The Silk Type mark, drawn inline: an image file wouldn't load from a paste,
// and a data: URL can be blocked by the page's CSP.
const LOGO = `<svg class="logo" viewBox="0 0 22 22" aria-hidden="true">
  <rect width="22" height="22" rx="5" fill="#fff"/>
  <g transform="translate(2.6 3) scale(.5)" fill="#6F59F4">
    <rect width="5.477" height="33.844" transform="matrix(1 0 -.3256 .9455 12.582 0)" fill-opacity=".2"/>
    <rect width="5.477" height="33.844" transform="matrix(1 0 -.3256 .9455 18.059 0)" fill-opacity=".5"/>
    <rect width="5.477" height="33.844" transform="matrix(1 0 -.3256 .9455 23.537 0)" fill-opacity=".8"/>
    <rect width="5.477" height="33.844" transform="matrix(1 0 -.3256 .9455 29.014 0)"/>
  </g>
</svg>`;

const VOID = new Set(['input', 'img', 'br', 'hr', 'meta', 'link']);
const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", hellip: '…' };
const decode = (s) => s.replace(/&(#?\w+);/g, (m, name) => ENTITIES[name] ?? m);

// Just enough HTML parsing for our own markup: elements, attributes, text,
// comments, void and self-closing tags. Tags and attributes keep their case,
// which SVG needs (viewBox, linearGradient). Whitespace-only text is dropped;
// everything it sat between is laid out by flex or grid.
function parse(html) {
  const top = { children: [] };
  const stack = [top];
  const token = /<!--[\s\S]*?-->|<\/([\w:-]+)\s*>|<([\w:-]+)((?:\s+[\w:-]+(?:="[^"]*")?)*)\s*(\/?)>|([^<]+)/g;
  for (const [, close, open, attrText, selfClose, text] of html.matchAll(token)) {
    const parent = stack.at(-1);
    if (close) {
      if (stack.at(-1).tag !== close) throw new Error(`</${close}> closes <${stack.at(-1).tag}>`);
      stack.pop();
    } else if (open) {
      const attrs = {};
      for (const [, name, value = ''] of attrText.matchAll(/([\w:-]+)(?:="([^"]*)")?/g)) attrs[name] = decode(value);
      const node = { tag: open, attrs, children: [] };
      parent.children.push(node);
      if (!selfClose && !VOID.has(open)) stack.push(node);
    } else if (text !== undefined && text.trim()) {
      parent.children.push(decode(text.replace(/\s+/g, ' ')));
    }
  }
  if (stack.length !== 1) throw new Error(`<${stack.at(-1).tag}> never closed`);
  const toTree = (n) => (typeof n === 'string' ? n : [n.tag, n.attrs, n.children.map(toTree)]);
  const elements = top.children.filter((n) => typeof n !== 'string');
  if (elements.length !== 1) throw new Error('expected one root element in the ui block');
  return toTree(elements[0]);
}

const html = read('extension/popup.html');
const start = html.indexOf('-->', html.indexOf('<!-- ui')) + 3;
const end = html.indexOf('<!-- /ui -->');
const markup = html.slice(start, end)
  .replace(/<img src="icons\/128\.png"[^>]*>/, LOGO)
  .replace(/ autofocus(?=[\s>])/g, '');
const tree = parse(markup);

const css = `${read('extension/popup.css')}\n${read('inject/menu.css')}`;
const indent = (src) => src.replace(/^(?=.)/gm, '  ');

const out = `// Smooth Caret, injectable build. Paste into a page's DevTools console (or
// save as a Sources > Snippets snippet and run it with Cmd+Enter). The caret
// starts right away; tap Right Shift to show or hide the settings menu.
// Running it again just opens the menu.
//
// Generated by inject/build.mjs from extension/ and inject/. Edit those and
// rebuild; don't edit this file.
(() => {
  'use strict';
  if (window.__smoothCaretMenu) {
    window.__smoothCaretMenu.toggle(true);
    return;
  }

  const UI_TREE = ${JSON.stringify(tree)};
  const UI_CSS = ${JSON.stringify(css)};

${indent(read('inject/store.js'))}
  // ---------- caret (extension/content.js), handed the stand-in chrome ----------
  ((chrome) => {
${indent(indent(read('extension/content.js')))}
  })(chromeShim);

  // ---------- settings UI (extension/ui.js) ----------
${indent(read('extension/ui.js'))}
  // ---------- menu window (inject/menu.js) ----------
${indent(read('inject/menu.js'))}})();
`;

mkdirSync(new URL('dist/', root), { recursive: true });
writeFileSync(new URL('dist/smooth-caret-inject.js', root), out);
console.log(`dist/smooth-caret-inject.js: ${(out.length / 1024).toFixed(1)} KB`);
